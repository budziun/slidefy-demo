import { 
  MOCK_USER, 
  MOCK_PLAYLISTS, 
  MOCK_TOP_TRACKS, 
  MOCK_BASE_ARTISTS,
  MOCK_ARTISTS_BY_TIME_RANGE,
  MOCK_TRACKS_BY_TIME_RANGE 
} from './mockData';

const STORAGE_KEYS = {
  PLAYLISTS: 'slidefy_mock_playlists_v7',
  USER: 'slidefy_mock_user'
};

const getStoredPlaylists = () => {
  try {
    const raw = localStorage.getItem(STORAGE_KEYS.PLAYLISTS);
    if (raw) {
      return JSON.parse(raw);
    }
  } catch (e) {
    console.error('Error reading mock playlists from localStorage', e);
  }
  // Initialize with default
  localStorage.setItem(STORAGE_KEYS.PLAYLISTS, JSON.stringify(MOCK_PLAYLISTS));
  return JSON.parse(JSON.stringify(MOCK_PLAYLISTS));
};

const savePlaylists = (playlists) => {
  localStorage.setItem(STORAGE_KEYS.PLAYLISTS, JSON.stringify(playlists));
};

export const mockApi = {
  getDashboard: async () => {
    return { ...MOCK_USER };
  },

  getToken: async () => {
    return { accessToken: 'demo-slidefy-token-xyz' };
  },

  getPlaylists: async () => {
    const playlists = getStoredPlaylists();
    // Return summary items as Spotify API does
    return playlists.map(p => ({
      id: p.id,
      name: p.name,
      description: p.description,
      images: p.images,
      owner: p.owner,
      tracks: { total: p.tracks.items.length }
    }));
  },

  getPlaylistById: async (id) => {
    const playlists = getStoredPlaylists();
    const playlist = playlists.find(p => p.id === id);
    if (!playlist) {
      const err = new Error('Playlist not found');
      err.response = { status: 404, data: { error: 'Playlist not found' } };
      throw err;
    }
    return {
      ...playlist,
      tracks: {
        ...playlist.tracks,
        total: playlist.tracks.items.length
      }
    };
  },

  removeTrack: async (playlistId, trackUri) => {
    const playlists = getStoredPlaylists();
    const index = playlists.findIndex(p => p.id === playlistId);
    if (index === -1) {
      const err = new Error('Playlist not found');
      err.response = { status: 404, data: { error: 'Playlist not found' } };
      throw err;
    }
    const playlist = playlists[index];
    playlist.tracks.items = playlist.tracks.items.filter(item => item.track.uri !== trackUri);
    playlist.tracks.total = playlist.tracks.items.length;
    savePlaylists(playlists);
    return { success: true };
  },

  deletePlaylist: async (playlistId) => {
    let playlists = getStoredPlaylists();
    const target = playlists.find(p => p.id === playlistId);
    playlists = playlists.filter(p => p.id !== playlistId);
    savePlaylists(playlists);
    return {
      success: true,
      message: 'Playlist deleted successfully',
      playlistName: target ? target.name : 'Unknown'
    };
  },

  getTopTracks: async (timeRange = 'short_term') => {
    return MOCK_TRACKS_BY_TIME_RANGE[timeRange] || MOCK_TOP_TRACKS;
  },

  getTopArtists: async (timeRange = 'short_term') => {
    return MOCK_ARTISTS_BY_TIME_RANGE[timeRange] || MOCK_BASE_ARTISTS;
  },

  createPlaylist: async ({ playlistName, timeRange, trackLimit = 20 }) => {
    const playlists = getStoredPlaylists();
    const newId = `pl-gen-${Date.now()}`;
    const selectedTracks = MOCK_TOP_TRACKS.slice(0, trackLimit).map(t => ({ track: t }));
    
    const existingCoverUrls = new Set(playlists.map(p => p.images?.[0]?.url).filter(Boolean));
    const uniqueTrack = selectedTracks.find(t => {
      const url = t.track?.album?.images?.[0]?.url;
      return url && !existingCoverUrls.has(url);
    });
    const coverUrl = uniqueTrack?.track?.album?.images?.[0]?.url 
      || selectedTracks[7]?.track?.album?.images?.[0]?.url 
      || selectedTracks[0]?.track?.album?.images?.[0]?.url 
      || "https://images.unsplash.com/photo-1514525253161-7a46d19cd819?w=500";

    const newPlaylist = {
      id: newId,
      name: playlistName,
      description: `Generated by Slidefy - Top ${selectedTracks.length} tracks (${timeRange})`,
      collaborative: false,
      owner: { id: "jakub-budzich", display_name: "Jakub Budzich" },
      images: [
        { url: coverUrl }
      ],
      tracks: {
        total: selectedTracks.length,
        items: selectedTracks
      }
    };

    playlists.unshift(newPlaylist);
    savePlaylists(playlists);

    return {
      message: 'Playlist created successfully!',
      playlistId: newId,
      trackCount: selectedTracks.length,
      playlistName: playlistName
    };
  },

  resetDemoData: () => {
    localStorage.setItem(STORAGE_KEYS.PLAYLISTS, JSON.stringify(MOCK_PLAYLISTS));
    window.dispatchEvent(new CustomEvent('playlistsUpdated'));
  }
};

